import { act, render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import App from "./App";
import { currentBoardRaw, makeBoard, makeTask } from "./test/fixtures";
import { decodeBoard, STORAGE_KEY } from "./utils/storage";

beforeEach(() => localStorage.clear());
afterEach(() => { vi.restoreAllMocks(); localStorage.clear(); });

it("keeps recovery active after dismissal/rerender, cancels safely by keyboard, and replaces only after confirmation", async () => {
  const original = "{private broken board";
  localStorage.setItem(STORAGE_KEY, original);
  localStorage.setItem("taskflow-view-preferences", "keep preferences");
  const write = vi.spyOn(Storage.prototype, "setItem");
  const user = userEvent.setup();
  const view = render(<App />);
  const alert = screen.getByRole("alert");
  await user.click(within(alert).getByRole("button", { name: /Dismiss notification/ }));
  expect(screen.queryByRole("alert")).not.toBeInTheDocument();
  expect(screen.getByRole("region", { name: "Board storage" })).toHaveTextContent("saving is paused");
  view.rerender(<App />);
  expect(screen.queryByRole("alert")).not.toBeInTheDocument();
  expect(write).not.toHaveBeenCalled();
  await user.click(screen.getByText("Troubleshooting details"));
  expect(screen.getByText("Recovery code: invalid-json")).toBeInTheDocument();
  expect(document.body.textContent).not.toContain("private broken board");
  const trigger = screen.getByRole("button", { name: "Replace saved board" });
  trigger.focus(); await user.keyboard("{Enter}");
  let dialog = screen.getByRole("dialog", { name: "Replace Saved Board?" });
  expect(dialog).toHaveAccessibleDescription(/cannot be undone/);
  expect(within(dialog).getByRole("button", { name: "Cancel" })).toHaveFocus();
  expect(localStorage.getItem(STORAGE_KEY)).toBe(original);
  await user.keyboard("{Escape}");
  await waitFor(() => expect(trigger).toHaveFocus());
  expect(write).not.toHaveBeenCalled();
  await user.keyboard("{Enter}");
  dialog = screen.getByRole("dialog", { name: "Replace Saved Board?" });
  await user.tab();
  expect(within(dialog).getByRole("button", { name: "Replace Saved Board" })).toHaveFocus();
  await user.keyboard("{Enter}");
  expect(screen.queryByRole("dialog")).not.toBeInTheDocument();
  expect(screen.queryByRole("region", { name: "Board storage" })).not.toBeInTheDocument();
  expect(decodeBoard(localStorage.getItem(STORAGE_KEY)).kind).toBe("current");
  expect(write).toHaveBeenCalledOnce();
  expect(localStorage.getItem("taskflow-view-preferences")).toBe("keep preferences");
  await waitFor(() => expect(screen.getByRole("button", { name: "+ Create Task" })).toHaveFocus());
});

it("reports failed replacement without losing the original and keeps confirmation available for retry", async () => {
  localStorage.setItem(STORAGE_KEY, "{broken");
  const user = userEvent.setup(); render(<App />);
  const write = vi.spyOn(Storage.prototype, "setItem").mockImplementationOnce(() => { throw new Error("Private failure"); });
  await user.click(screen.getByRole("button", { name: "Replace saved board" }));
  await user.click(within(screen.getByRole("dialog")).getByRole("button", { name: "Replace Saved Board" }));
  expect(screen.getByRole("alert")).toHaveTextContent("could not confirm");
  expect(screen.getByRole("alert")).not.toHaveTextContent("Private failure");
  expect(localStorage.getItem(STORAGE_KEY)).toBe("{broken");
  expect(screen.getByRole("region", { name: "Board storage" })).toHaveTextContent("Saving is paused");
  expect(write).toHaveBeenCalledTimes(1);
  await user.click(screen.getByRole("button", { name: "Replace saved board" }));
  await user.click(within(screen.getByRole("dialog")).getByRole("button", { name: "Replace Saved Board" }));
  expect(screen.queryByRole("alert")).not.toBeInTheDocument();
  expect(write).toHaveBeenCalledTimes(2);
});

it("confirms discarding temporary work on successful read retry, while canceling retains it", async () => {
  const original = currentBoardRaw();
  localStorage.setItem(STORAGE_KEY, original);
  const actualGet = Storage.prototype.getItem;
  const read = vi.spyOn(Storage.prototype, "getItem").mockImplementation(() => { throw new Error("Private read exception"); });
  const write = vi.spyOn(Storage.prototype, "setItem");
  const user = userEvent.setup(); render(<App />);
  expect(screen.getByRole("alert")).toHaveTextContent("Browser storage is unavailable");
  expect(screen.queryByRole("button", { name: "Replace saved board" })).not.toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "+ Create Task" }));
  await user.type(screen.getByLabelText("Title"), "Temporary work");
  await user.type(screen.getByLabelText("Description"), "Details");
  await user.click(screen.getByRole("button", { name: "Create Task" }));
  expect(write).not.toHaveBeenCalled();
  await user.click(screen.getByRole("button", { name: "Retry reading saved board" }));
  await user.click(within(screen.getByRole("dialog")).getByRole("button", { name: "Cancel" }));
  expect(screen.getByRole("button", { name: "Open task Temporary work" })).toBeInTheDocument();
  read.mockRestore();
  await user.click(screen.getByRole("button", { name: "Retry reading saved board" }));
  await user.click(within(screen.getByRole("dialog")).getByRole("button", { name: "Retry Reading" }));
  expect(screen.getByRole("button", { name: "Open task Build search" })).toBeInTheDocument();
  expect(screen.queryByRole("button", { name: "Open task Temporary work" })).not.toBeInTheDocument();
  expect(screen.queryByRole("region", { name: "Board storage" })).not.toBeInTheDocument();
  expect(actualGet.call(localStorage, STORAGE_KEY)).toBe(original);
  expect(write).not.toHaveBeenCalled();
});

it("preserves corrupt data across remounts even after temporary task creation", async () => {
  localStorage.setItem(STORAGE_KEY, "{broken");
  const user = userEvent.setup(); const view = render(<App />);
  await user.click(screen.getByRole("button", { name: "+ Create Task" }));
  await user.type(screen.getByLabelText("Title"), "Temporary work");
  await user.type(screen.getByLabelText("Description"), "Details");
  await user.click(screen.getByRole("button", { name: "Create Task" }));
  expect(localStorage.getItem(STORAGE_KEY)).toBe("{broken");
  view.unmount(); render(<App />);
  expect(screen.getByRole("alert")).toHaveTextContent("An empty workspace is open");
  expect(screen.queryByRole("button", { name: "Open task Temporary work" })).not.toBeInTheDocument();
  expect(localStorage.getItem(STORAGE_KEY)).toBe("{broken");
});

it("cancels and confirms selective order repair while retaining tasks and avoiding duplicate announcements", async () => {
  const board = makeBoard([makeTask({ id: "a", title: "Alpha", priority: "low" }), makeTask({ id: "b", title: "Beta", priority: "high" })]);
  const data = JSON.parse(currentBoardRaw(board));
  data.board.columns[0].manualOrder = ["a", "a"];
  const original = JSON.stringify(data);
  localStorage.setItem(STORAGE_KEY, original);
  const write = vi.spyOn(Storage.prototype, "setItem");
  const user = userEvent.setup(); const view = render(<App />);
  const problem = screen.getAllByRole("status").find(node => node.textContent?.includes("saved manual order needs repair"))!;
  view.rerender(<App />);
  expect(screen.getAllByRole("status").find(node => node.textContent?.includes("saved manual order needs repair"))).toBe(problem);
  await user.click(screen.getByRole("button", { name: "Repair saved order" }));
  let dialog = screen.getByRole("dialog", { name: "Repair Saved Order?" });
  expect(dialog).toHaveAccessibleDescription(/relationships and valid saved order will be kept/);
  await user.click(within(dialog).getByRole("button", { name: "Cancel" }));
  expect(write).not.toHaveBeenCalled();
  await user.click(screen.getByRole("button", { name: "Repair saved order" }));
  dialog = screen.getByRole("dialog", { name: "Repair Saved Order?" });
  await user.click(within(dialog).getByRole("button", { name: "Repair Saved Order" }));
  expect(screen.queryByRole("region", { name: "Board storage" })).not.toBeInTheDocument();
  expect(JSON.parse(localStorage.getItem(STORAGE_KEY)!).board.columns[0].manualOrder).toEqual(["b", "a"]);
  expect(write).toHaveBeenCalledOnce();
  expect(screen.getByRole("button", { name: "Open task Alpha" })).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "Open task Beta" })).toBeInTheDocument();
  act(() => view.rerender(<App />));
  expect(write).toHaveBeenCalledOnce();
});
